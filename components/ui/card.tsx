import * as React from "react";
import { cn } from "@/lib/utils";

/*
  One border, at most one soft shadow. The shadow token resolves to none in dark,
  where the border carries the separation instead. Never nest cards.
*/
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[var(--radius-md)] border border-border bg-card text-card-foreground",
      "shadow-[var(--shadow-sm)]",
      interactive &&
        "transition-colors duration-[120ms] ease-out hover:border-primary",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

export const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div ref={ref} className={cn("flex flex-col gap-1 p-4", className)} {...props} />
));
CardHeader.displayName = "CardHeader";

